type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>(() => {
    const stored = window.localStorage.getItem("agent_service_console_language");
    return stored === "en" ? "en" : "es";
  });
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const setLanguage = (next: Language) => {
    window.localStorage.setItem("agent_service_console_language", next);
    document.documentElement.lang = next;
    updateLanguage(next);
  };
  const value = useMemo(() => ({ language, setLanguage, t: (text: string) => language === "en" ? english[text] ?? text : text }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("LanguageProvider is missing");
  return context;
}
